def greet(name):
    return f"Hi, {name}! Glad to have you here."

def farewell(name):
    return f"Goodbye, {name}, see you next time!"

def thank_you(name):
    return f"Thank you, {name}!"

def goodnight(name):
    return f"Goodnight, {name}! Sleep well!"

if __name__ == "__main__":
    print(greet("World"))
    print(farewell("World"))
